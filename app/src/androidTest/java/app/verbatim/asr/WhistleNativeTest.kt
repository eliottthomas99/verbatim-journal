package app.verbatim.asr

import android.content.ContextWrapper
import android.net.TrafficStats
import android.os.Process
import androidx.test.platform.app.InstrumentationRegistry
import org.junit.Assert.*
import org.junit.Test
import java.io.File
import java.nio.ByteBuffer
import java.nio.ByteOrder

class WhistleNativeTest {
    private val instrumentation = InstrumentationRegistry.getInstrumentation()
    private val context = instrumentation.targetContext

    @Test fun speechModelLoadsAndSilenceIsEmpty() {
        WhistleNative.loadModelFromAssets(context).getOrThrow()
        assertTrue(WhistleNative.isModelLoaded())
        val result = WhistleNative.transcribe(FloatArray(32000)).getOrThrow()
        assertEquals("", result.text)
        assertEquals("", result.language)
        assertTrue(result.words.isEmpty())
    }

    @Test fun invalidPcmFailsInsteadOfEnteringNativeEngine() {
        WhistleNative.loadModelFromAssets(context).getOrThrow()
        assertTrue(WhistleNative.transcribe(floatArrayOf(Float.NaN)).isFailure)
        assertTrue(WhistleNative.transcribe(floatArrayOf(2f)).isFailure)
    }

    @Test fun corruptPrivateCopyIsRepairedFromBundledAsset() {
        val isolated = File(context.cacheDir, "whistle-integrity-test")
        val testContext = object : ContextWrapper(context) {
            override fun getFilesDir(): File = isolated
        }
        try {
            val file = File(isolated, "whistle/whistle.cact")
            file.parentFile!!.mkdirs()
            file.writeText("partial")
            assertEquals(16_919_407L, WhistleNative.prepareModel(testContext).length())
            val timestamp = file.lastModified()
            assertEquals(file, WhistleNative.prepareModel(testContext))
            assertEquals(timestamp, file.lastModified())
            assertFalse(File(file.parentFile, "whistle.cact.part").exists())
        } finally {
            // Only this test's temporary model copy, never the user's app data.
            File(isolated, "whistle/whistle.cact").delete()
            File(isolated, "whistle/whistle.cact.part").delete()
            File(isolated, "whistle").delete()
            isolated.delete()
        }
    }

    @Test fun englishIsDetectedAutomatically() {
        WhistleNative.loadModelFromAssets(context).getOrThrow()
        val result = WhistleNative.transcribe(readPcm("english.wav")).getOrThrow()
        assertEquals("en", result.language)
        assertTrue(result.text.contains("speech", ignoreCase = true))
        assertTrue(result.words.isNotEmpty())
    }

    @Test fun frenchIsDetectedAndAccentsSurviveJni() {
        WhistleNative.loadModelFromAssets(context).getOrThrow()
        val result = WhistleNative.transcribe(readPcm("french.wav")).getOrThrow()
        assertEquals("fr", result.language)
        assertTrue(result.text.contains("téléphone", ignoreCase = true))
        assertTrue(result.words.isNotEmpty())
        assertTrue(result.words.all { it.start >= 0 && it.end >= it.start })
    }

    @Test fun inferenceDoesNotTransmitNetworkBytes() {
        WhistleNative.loadModelFromAssets(context).getOrThrow()
        val pcm = readPcm("french.wav")
        val before = TrafficStats.getUidTxBytes(Process.myUid())
        assertTrue("Per-app network accounting must be available", before >= 0)
        WhistleNative.transcribe(pcm).getOrThrow()
        Thread.sleep(500)
        assertEquals(before, TrafficStats.getUidTxBytes(Process.myUid()))
    }

    private fun readPcm(name: String): FloatArray {
        // Fixtures are generated by tools/generate_whistle_test_audio.ps1.
        val bytes = instrumentation.context.assets.open(name).use { it.readBytes() }
        val buffer = ByteBuffer.wrap(bytes).order(ByteOrder.LITTLE_ENDIAN)
        var position = 12
        while (position + 8 <= bytes.size) {
            val kind = String(bytes, position, 4, Charsets.US_ASCII)
            val size = buffer.getInt(position + 4)
            require(size >= 0 && size <= bytes.size - position - 8)
            if (kind == "fmt ") {
                require(buffer.getShort(position + 8).toInt() == 1)
                require(buffer.getShort(position + 10).toInt() == 1)
                require(buffer.getInt(position + 12) == 16000)
                require(buffer.getShort(position + 22).toInt() == 16)
            }
            if (kind == "data") {
                return FloatArray(size / 2) { buffer.getShort(position + 8 + it * 2) / 32768f }
            }
            position += 8 + size + (size and 1)
        }
        error("Missing PCM test data")
    }
}
